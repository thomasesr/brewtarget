"""Generate the Rust row structs and enums for `bt-model`.

Input is `schema/v23.json` and `schema/enums.json`; output is checked into git so that builds are
hermetic and a schema change shows up as a reviewable diff.

    python3 tools/generate-model.py --out rust/crates/bt-model/src/generated

See PLAN.md Phase 4.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent

# No column in the v23 schema is NOT NULL, so every one of them can come back as NULL.  Rather
# than guess which are really required, every field but the primary key is optional.
RUST_TYPES = {"bool": "bool", "int": "i64", "uint": "i64", "double": "f64", "string": "String", "date": "NaiveDate"}

RUST_KEYWORDS = {"type", "use", "ref", "match", "move", "box", "enum", "fn", "impl", "let", "loop", "mod", "self"}

HEADER = """// SPDX-License-Identifier: GPL-3.0-or-later
//
// bt-model/src/generated/{file} is part of Brewtarget, and is copyright the following authors 2026:
//   • The Brewtarget contributors
//
// Brewtarget is free software: you can redistribute it and/or modify it under the terms of the GNU General Public
// License as published by the Free Software Foundation, either version 3 of the License, or (at your option) any later
// version.  See <http://www.gnu.org/licenses/>.

// @generated by tools/generate-model.py from {sources}.  Do not edit by hand.
"""


def pascal_case(name: str) -> str:
    """For snake_case input: `folder_for_hop` becomes `FolderForHop`."""
    return "".join(part.capitalize() for part in re.split(r"[_\s]+", name) if part)


def type_case(name: str) -> str:
    """Capitalise without flattening camel case: `chillingType` becomes `ChillingType`.

    `str.capitalize` would give `Chillingtype`, and `BoilStep` would become `Boilstep`.
    """
    return "".join(part[0].upper() + part[1:] for part in re.split(r"[_\s]+", name) if part)


def variant_name(member: str) -> str:
    """A C++ enum member as a Rust variant.

    Most are already upper camel case; a few are written `Dry_Extract`, which Rust will complain
    about.  Only the spelling changes -- the string stored in the database is untouched.
    """
    return type_case(member)


def field_name(column: str) -> str:
    """A column name as a Rust field, escaping the one that collides with a keyword."""
    name = re.sub(r"(?<!^)(?=[A-Z])", "_", column).lower()
    return f"r#{name}" if name in RUST_KEYWORDS else name


def generate_enums(enums: dict) -> str:
    """One Rust enum per mapping, with the exact strings the database stores."""
    out = [
        HEADER.format(file="enums.rs", sources="schema/enums.json"),
        "",
        "//! The enumerations stored as strings in the database.",
        "//!",
        "//! The string forms are on-disk data and are reproduced exactly as `src/model/` declares",
        "//! them, so that a database written here still reads back in the C++ application.",
        "",
        "use std::fmt;",
        "",
        "/// A string in the database that no member of the enumeration corresponds to.",
        "#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]",
        '#[error("{value:?} is not a valid {enumeration}")]',
        "pub struct UnknownValue {",
        "    pub enumeration: &'static str,",
        "    pub value: String,",
        "}",
        "",
    ]

    for name, mapping in enums["mappings"].items():
        if mapping.get("by_object_address"):
            continue  # units are handled by bt-measure, which owns the unit table
        type_name = type_case(mapping["owner"].split("::")[-1]) + type_case(
            mapping["name"].removesuffix("StringMapping")
        )
        out += [
            f"/// `{name}`, declared in `{mapping['source_file']}`.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
            f"pub enum {type_name} {{",
        ]
        for value in mapping["values"]:
            renamed = "" if variant_name(value["member"]) == value["member"] else f" C++ `{value['member']}`."
            out.append(f"    /// Stored as `{value['string']}`.{renamed}")
            out.append(f"    {variant_name(value['member'])},")
        out += ["}", "", f"impl {type_name} {{", "    /// The string this member is stored as.", "    pub fn as_str(&self) -> &'static str {", "        match self {"]
        for value in mapping["values"]:
            out.append(f'            Self::{variant_name(value["member"])} => "{value["string"]}",')
        out += [
            "        }",
            "    }",
            "",
            "    /// Every member, in the order the C++ declares them.",
            f"    pub const ALL: [Self; {len(mapping['values'])}] = [",
        ]
        for value in mapping["values"]:
            out.append(f"        Self::{variant_name(value['member'])},")
        out += [
            "    ];",
            "}",
            "",
            f"impl std::str::FromStr for {type_name} {{",
            "    type Err = UnknownValue;",
            "",
            "    fn from_str(value: &str) -> Result<Self, Self::Err> {",
            "        Self::ALL",
            "            .into_iter()",
            "            .find(|member| member.as_str() == value)",
            f'            .ok_or_else(|| UnknownValue {{ enumeration: "{type_name}", value: value.to_owned() }})',
            "    }",
            "}",
            "",
            f"impl fmt::Display for {type_name} {{",
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
            "        f.write_str(self.as_str())",
            "    }",
            "}",
            "",
        ]
    return "\n".join(out)


def generate_tables(schema: dict) -> str:
    """One Rust struct per table, mirroring its columns exactly."""
    out = [
        HEADER.format(file="tables.rs", sources="schema/v23.json"),
        "",
        "//! A row of each table in the v23 schema.",
        "//!",
        "//! These are the shape of the database, not the shape of the domain: a `Recipe` here is a",
        "//! `recipe` row, nothing more.  Behaviour belongs on the hand-written types that wrap them.",
        "//!",
        "//! No column in the v23 schema is `NOT NULL`, so every field but the primary key is",
        "//! optional.  That is the schema being honest rather than this being cautious -- which",
        "//! fields a row really requires is decided by the model classes in `src/model/`, not by the",
        "//! database.",
        "",
        "use chrono::NaiveDate;",
        "use serde::{Deserialize, Serialize};",
        "",
    ]

    for table in schema["tables"]:
        struct = pascal_case(table["name"]) + "Row"
        out += [
            f"/// A row of `{table['name']}`, which stores `{table['cpp_type']}`.",
            "#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]",
            f"pub struct {struct} {{",
            f"    /// `{table['primary_key']['name']}`",
            f"    pub {field_name(table['primary_key']['name'])}: i64,",
        ]
        for column in table["columns"]:
            rust_type = RUST_TYPES[column["base_type"]]
            note = f" Stored via `{column['string_mapping']}`." if column["string_mapping"] else ""
            inherited = f" Inherited from `{column['from_common_set']}`." if column["from_common_set"] else ""
            out.append(f"    /// `{column['name']}` ({column['field_type']}).{note}{inherited}")
            out.append(f"    pub {field_name(column['name'])}: Option<{rust_type}>,")
        for key in table["foreign_keys"]:
            out.append(f"    /// `{key['column']}` referencing `{key['references_table']}.{key['references_column']}`.")
            out.append(f"    pub {field_name(key['column'])}: Option<i64>,")
        out += ["}", "", f"impl {struct} {{", f'    pub const TABLE: &\'static str = "{table["name"]}";', "}", ""]

    out += [
        "/// Every table in the schema, in the order `schema/v23.json` lists them.",
        f"pub const TABLES: [&str; {len(schema['tables'])}] = [",
    ]
    for table in schema["tables"]:
        out.append(f'    "{table["name"]}",')
    out += ["];", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=pathlib.Path, required=True, help="directory to write the Rust files into")
    args = parser.parse_args()

    schema = json.loads((REPO / "schema" / "v23.json").read_text(encoding="utf-8"))
    enums = json.loads((REPO / "schema" / "enums.json").read_text(encoding="utf-8"))

    args.out.mkdir(parents=True, exist_ok=True)
    files = {"enums.rs": generate_enums(enums), "tables.rs": generate_tables(schema)}
    files["mod.rs"] = (
        HEADER.format(file="mod.rs", sources="schema/v23.json and schema/enums.json")
        + "\n//! Generated model code.  See `tools/generate-model.py`.\n\npub mod enums;\npub mod tables;\n"
    )
    written = []
    for name, content in files.items():
        path = args.out / name
        path.write_text(content.rstrip("\n") + "\n", encoding="utf-8")
        written.append(path)
        print(f"wrote {path}")

    # Format what was generated, so that the committed files are byte-identical to a fresh run and
    # `cargo fmt --check` has nothing to say about them.
    rustfmt = shutil.which("rustfmt")
    if rustfmt:
        # Point rustfmt at the workspace config explicitly: it searches upwards from each file,
        # so generating into a scratch directory would otherwise use different settings and the
        # output would not match what is committed.
        config = REPO / "rust" / "rustfmt.toml"
        subprocess.run(
            [rustfmt, "--edition", "2024", "--config-path", str(config), *[str(path) for path in written]],
            check=True,
        )
        print(f"formatted {len(written)} files")
    else:
        print("warning: rustfmt not found; generated files are unformatted", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
