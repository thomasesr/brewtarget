def pascal_case(name: str) -> str:
    """For snake_case input: `folder_for_hop` becomes `FolderForHop`."""
    return "".join(part.capitalize() for part in re.split(r"[_\s]+", name) if part)


def type_case(name: str) -> str:
    """Capitalise without flattening camel case: `chillingType` becomes `ChillingType`.

    `str.capitalize` would give `Chillingtype`, and `BoilStep` would become `Boilstep`.  A part
    that is entirely upper case came from a SCREAMING_SNAKE name, though -- the serialization code
    declares its mappings that way -- and has to be lowered first, or `BEER_XML_HOP_FORM_MAPPER`
    comes out as `BEERXMLHOPFORMMAPPER`.
    """
    parts = []
    for part in re.split(r"[_\s]+", name):
        if not part:
            continue
        if part.isupper() and len(part) > 1:
            part = part.capitalize()
        parts.append(part[0].upper() + part[1:])
    return "".join(parts)


def variant_name(member: str) -> str:
    """A C++ enum member as a Rust variant.

    Most are already upper camel case; a few are written `Dry_Extract`, which Rust will complain
    about.  Only the spelling changes -- the string stored in the database is untouched.
    """
    return type_case(member)


def field_name(column: str) -> str:
    """A column name as a Rust field, escaping the one that collides with a keyword."""
    name = re.sub(r"(?<!^)(?=[A-Z])", "_", column).lower()
    return f"r#{name}" if name in RUST_KEYWORDS else name


def generate_enums(enums: dict) -> str:
    """One Rust enum per mapping, with the exact strings the database stores."""
    out = [
        HEADER.format(file="enums.rs", sources="schema/enums.json"),
        "",
        "//! The enumerations stored as strings in the database.",
        "//!",
        "//! The string forms are on-disk data and are reproduced exactly as `src/model/` declares",
        "//! them, so that a database written here still reads back in the C++ application.",
        "",
        "use std::fmt;",
        "",
        "/// A string in the database that no member of the enumeration corresponds to.",
        "#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]",
        '#[error("{value:?} is not a valid {enumeration}")]',
        "pub struct UnknownValue {",
        "    pub enumeration: &'static str,",
        "    pub value: String,",
        "}",
        "",
    ]

    for name, mapping in enums["mappings"].items():
        if mapping.get("by_object_address"):
            continue  # units are handled by bt-measure, which owns the unit table
        type_name = type_case(mapping["owner"].split("::")[-1]) + type_case(
            mapping["name"].removesuffix("StringMapping")
        )
        out += [
            f"/// `{name}`, declared in `{mapping['source_file']}`.",
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]",
            f"pub enum {type_name} {{",
        ]
        for value in mapping["values"]:
            renamed = "" if variant_name(value["member"]) == value["member"] else f" C++ `{value['member']}`."
            out.append(f"    /// Stored as `{value['string']}`.{renamed}")
            out.append(f"    {variant_name(value['member'])},")
        out += ["}", "", f"impl {type_name} {{", "    /// The string this member is stored as.", "    pub fn as_str(&self) -> &'static str {", "        match self {"]
        for value in mapping["values"]:
            out.append(f'            Self::{variant_name(value["member"])} => "{value["string"]}",')
        out += [
            "        }",
            "    }",
            "",
            "    /// Every member, in the order the C++ declares them.",
            f"    pub const ALL: [Self; {len(mapping['values'])}] = [",
        ]
        for value in mapping["values"]:
            out.append(f"        Self::{variant_name(value['member'])},")
        out += [
            "    ];",
            "}",
            "",
            f"impl std::str::FromStr for {type_name} {{",
            "    type Err = UnknownValue;",
            "",
            "    fn from_str(value: &str) -> Result<Self, Self::Err> {",
            "        Self::ALL",
            "            .into_iter()",
            "            .find(|member| member.as_str() == value)",
            f'            .ok_or_else(|| UnknownValue {{ enumeration: "{type_name}", value: value.to_owned() }})',
            "    }",
            "}",
            "",
            f"impl fmt::Display for {type_name} {{",
            "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
            "        f.write_str(self.as_str())",
            "    }",
            "}",
            "",
        ]
    return "\n".join(out)


def rename_attribute(column: str) -> list[str]:
    """Tell sqlx and serde the column name when the Rust field is spelled differently."""
    name = field_name(column).removeprefix("r#")
    return [] if name == column else [f'    #[sqlx(rename = "{column}")]', f'    #[serde(rename = "{column}")]']


def enum_type_name(mapping_name: str) -> str:
    """The Rust enum a `string_mapping` refers to, named the same way `generate_enums` names it."""
    owner, _, name = mapping_name.rpartition("::")
    return type_case(owner.split("::")[-1]) + type_case(name.removesuffix("StringMapping"))


def generate_accessors(table: dict) -> list[str]:
    """Typed getters and setters for the columns that hold an enum or a unit name.

    Those columns store a string, so reading one back means parsing it.  Generating the accessors
    keeps them in step with `schema/enums.json` and spares 33 hand-written pairs.
    """
    struct = pascal_case(table["name"]) + "Row"
    out = []
    for column in table["columns"]:
        mapping = column["string_mapping"]
        if not mapping:
            continue
        field = field_name(column["name"])
        # The getter keeps the raw identifier where the column name is a Rust keyword; the setter
        # has `set_` in front of it and so needs no escaping.
        accessor = field.removeprefix("r#")
        if column["field_type"] == "Unit":
            out += [
                f"    /// `{column['name']}`, which holds a unit's name.",
                f"    pub fn {field}(&self) -> Option<Unit> {{",
                f"        self.{field}.as_deref().and_then(Unit::by_name)",
                "    }",
                "",
                f"    pub fn set_{accessor}(&mut self, unit: Option<Unit>) {{",
                f"        self.{field} = unit.map(|unit| unit.name().to_owned());",
                "    }",
                "",
            ]
        elif column["field_type"] == "Enum":
            enum = enum_type_name(mapping)
            out += [
                f"    /// `{column['name']}`, stored via `{mapping}`.",
                "    ///",
                "    /// `Err` means the column holds a string this version does not recognise, which is",
                "    /// worth surfacing rather than silently treating as absent.",
                f"    pub fn {field}(&self) -> Result<Option<{enum}>, UnknownValue> {{",
                f"        self.{field}.as_deref().map({enum}::from_str).transpose()",
                "    }",
                "",
                f"    pub fn set_{accessor}(&mut self, value: Option<{enum}>) {{",
                f"        self.{field} = value.map(|value| value.as_str().to_owned());",
                "    }",
                "",
            ]
    if not out:
        return []
    return [f"impl {struct} {{", *out[:-1], "}", ""]


def generate_tables(schema: dict) -> str:
    """One Rust struct per table, mirroring its columns exactly."""
    out = [
        HEADER.format(file="tables.rs", sources="schema/v23.json"),
        "",
        "//! A row of each table in the v23 schema.",
        "//!",
        "//! These are the shape of the database, not the shape of the domain: a `Recipe` here is a",
        "//! `recipe` row, nothing more.  Behaviour belongs on the hand-written types that wrap them.",
        "//!",
        "//! No column in the v23 schema is `NOT NULL`, so every field but the primary key is",
        "//! optional.  That is the schema being honest rather than this being cautious -- which",
        "//! fields a row really requires is decided by the model classes in `src/model/`, not by the",
        "//! database.",
        "",
        "use std::str::FromStr;",
        "",
        "use bt_measure::Unit;",
        "use chrono::NaiveDate;",
        "use serde::{Deserialize, Serialize};",
        "",
        "use crate::enums::*;",
        "",
        "// `sqlx::FromRow` reads a row straight into one of these.  Fields whose Rust spelling",
        "// differs from the column name carry an explicit rename, so the two cannot drift.",
        "",
    ]

    for table in schema["tables"]:
        struct = pascal_case(table["name"]) + "Row"
        out += [
            f"/// A row of `{table['name']}`, which stores `{table['cpp_type']}`.",
            "#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize, sqlx::FromRow)]",
            f"pub struct {struct} {{",
            f"    /// `{table['primary_key']['name']}`, which the database assigns.",
            "    ///",
            "    /// Defaults to zero so that a row read out of a file -- which has no database",
            "    /// identity until it is stored -- deserialises without one.",
            "    #[serde(default)]",
            *rename_attribute(table["primary_key"]["name"]),
            f"    pub {field_name(table['primary_key']['name'])}: i64,",
        ]
        for column in table["columns"]:
            rust_type = RUST_TYPES[column["base_type"]]
            note = f" Stored via `{column['string_mapping']}`." if column["string_mapping"] else ""
            inherited = f" Inherited from `{column['from_common_set']}`." if column["from_common_set"] else ""
            out.append(f"    /// `{column['name']}` ({column['field_type']}).{note}{inherited}")
            out += rename_attribute(column["name"])
            out.append(f"    pub {field_name(column['name'])}: Option<{rust_type}>,")
        for key in table["foreign_keys"]:
            out.append(f"    /// `{key['column']}` referencing `{key['references_table']}.{key['references_column']}`.")
            out += rename_attribute(key["column"])
            out.append(f"    pub {field_name(key['column'])}: Option<i64>,")
        columns = (
            [table["primary_key"]["name"]]
            + [column["name"] for column in table["columns"]]
            + [key["column"] for key in table["foreign_keys"]]
        )
        out += [
            "}",
            "",
            f"impl {struct} {{",
            f'    pub const TABLE: &\'static str = "{table["name"]}";',
            f'    pub const PRIMARY_KEY: &\'static str = "{table["primary_key"]["name"]}";',
            "    /// Every column, primary key first, then the ordinary columns, then the foreign keys.",
            f"    pub const COLUMNS: [&'static str; {len(columns)}] = [",
        ]
        out += [f'        "{column}",' for column in columns]
        out += ["    ];", "}", ""]
        out += generate_accessors(table)

    out += [
        "/// Every table in the schema, in the order `schema/v23.json` lists them.",
        f"pub const TABLES: [&str; {len(schema['tables'])}] = [",
    ]
    for table in schema["tables"]:
        out.append(f'    "{table["name"]}",')
    out += ["];", ""]

    # The interchange formats name a model property rather than a column, so a reader needs to
    # get from one to the other.  The schema records both, so the map is generated rather than
    # written out.
    out += [
        "/// The table that stores a given C++ model class, e.g. `Hop` is kept in `hop`.",
        "pub fn table_for_cpp_type(cpp_type: &str) -> Option<&'static str> {",
        "    match cpp_type {",
    ]
    for table in schema["tables"]:
        out.append(f'        "{table["cpp_type"]}" => Some("{table["name"]}"),')
    out += [
        "        _ => None,",
        "    }",
        "}",
        "",
        "/// The column a model property is stored in, e.g. `Hop::alpha_pct` is kept in",
        "/// `hop.alpha_pct`.",
        "///",
        "/// A property may appear on several tables -- every table has `NamedEntity::name` -- so the",
        "/// table has to be named too.",
        "pub fn column_for_property(table: &str, property: &str) -> Option<&'static str> {",
        "    match (table, property) {",
    ]
    for table in schema["tables"]:
        seen = set()
        entries = []
        if table["primary_key"]["property"]:
            entries.append((table["primary_key"]["property"], table["primary_key"]["name"]))
        entries += [(column["property"], column["name"]) for column in table["columns"] if column["property"]]
        entries += [(key["property"], key["column"]) for key in table["foreign_keys"] if key["property"]]
        for property_name, column in entries:
            if property_name in seen:
                continue
            seen.add(property_name)
            out.append(f'        ("{table["name"]}", "{property_name}") => Some("{column}"),')
    out += ["        _ => None,", "    }", "}", ""]

    out += [
        "/// Every column of a table, primary key first.",
        "///",
        "/// Used to check a column name before it reaches SQL: column names cannot be bound as",
        "/// parameters, so anything interpolated into a statement has to be known to be one of these.",
        "pub fn columns_of(table: &str) -> Option<&'static [&'static str]> {",
        "    match table {",
    ]
    for table in schema["tables"]:
        struct = pascal_case(table["name"]) + "Row"
        out.append(f'        "{table["name"]}" => Some(&{struct}::COLUMNS),')
    out += ["        _ => None,", "    }", "}", ""]

    out += [
        "/// Whether a column holds a true/false value.",
        "///",
        "/// Needed when a row is read back without a struct to deserialise into: SQLite keeps a",
        "/// BOOLEAN as 0 or 1 and MySQL as a TINYINT, so what the column means has to come from the",
        "/// schema rather than from what the database hands back.",
        "pub fn is_boolean_column(table: &str, column: &str) -> bool {",
        "    matches!(",
        "        (table, column),",
    ]
    booleans = [
        f'("{table["name"]}", "{column["name"]}")'
        for table in schema["tables"]
        for column in table["columns"]
        if column["field_type"] == "Bool"
    ]
    out.append("        " + " | ".join(booleans))
    out += ["    )", "}", ""]
    return "\n".join(out)


def generate_store(schema: dict) -> str:
    """One module per table: insert, get, list, update, delete, and a soft delete."""
    out = [
        HEADER.format(file="tables.rs", sources="schema/v23.json"),
        "",
        "//! A repository per table.",
        "//!",
        "//! Replaces `ObjectStoreTyped` from `src/database/`.  Every function takes the [`Store`]",
        "//! it should act on; there is no global pool and no ambient current database.",
        "//!",
        "//! `INSERT ... RETURNING id` is used to read back the generated key.  SQLite has supported",
        "//! it since 3.35, PostgreSQL always has, and MariaDB since 10.5 -- which is why MariaDB is",
        "//! the supported MySQL-family backend rather than MySQL itself.",
        "#![allow(clippy::needless_question_mark)]",
        "// Columns are bound uniformly as `&row.field`.  For the Copy types among them clippy would",
        "// rather see the value, but varying the generated code per column type buys nothing.",
        "#![allow(clippy::needless_borrows_for_generic_args)]",
        "",
        "use bt_model::tables::*;",
        "",
        "use crate::{Store, StoreError, dispatch};",
        "",
    ]

    for table in schema["tables"]:
        struct = pascal_case(table["name"]) + "Row"
        module = table["name"]
        primary_key = table["primary_key"]["name"]
        writable = [column["name"] for column in table["columns"]] + [k["column"] for k in table["foreign_keys"]]
        placeholders = ", ".join("?" for _ in writable)
        assignments = ", ".join(f"{column} = ?" for column in writable)
        column_list = ", ".join(writable)

        out += [
            f"/// Rows of `{table['name']}`.",
            f"pub mod {module} {{",
            "    use super::*;",
            "",
            f"    const INSERT: &str = \"INSERT INTO {table['name']} ({column_list}) VALUES ({placeholders}) RETURNING {primary_key}\";",
            f"    const UPDATE: &str = \"UPDATE {table['name']} SET {assignments} WHERE {primary_key} = ?\";",
            f"    const SELECT_ONE: &str = \"SELECT * FROM {table['name']} WHERE {primary_key} = ?\";",
            f"    const SELECT_ALL: &str = \"SELECT * FROM {table['name']}\";",
            f"    const DELETE: &str = \"DELETE FROM {table['name']} WHERE {primary_key} = ?\";",
            "",
            "    /// Insert a row and return the key the database generated for it.",
            f"    pub async fn insert(store: &Store, row: &{struct}) -> Result<i64, StoreError> {{",
            "        let sql = store.placeholders(INSERT);",
            "        dispatch!(store, |pool| {",
            "            Ok(sqlx::query_scalar(&sql)",
        ]
        out += [f"                .bind(&row.{field_name(column)})" for column in writable]
        out += [
            "                .fetch_one(pool)",
            "                .await?)",
            "        })",
            "    }",
            "",
            "    /// Overwrite every column of an existing row.",
            f"    pub async fn update(store: &Store, row: &{struct}) -> Result<(), StoreError> {{",
            "        let sql = store.placeholders(UPDATE);",
            "        dispatch!(store, |pool| {",
            "            sqlx::query(&sql)",
        ]
        out += [f"                .bind(&row.{field_name(column)})" for column in writable]
        out += [
            f"                .bind(row.{field_name(primary_key)})",
            "                .execute(pool)",
            "                .await?;",
            "            Ok(())",
            "        })",
            "    }",
            "",
            "    /// Read one row by its primary key.",
            f"    pub async fn get(store: &Store, id: i64) -> Result<Option<{struct}>, StoreError> {{",
            "        let sql = store.placeholders(SELECT_ONE);",
            "        dispatch!(store, |pool| {",
            f"            Ok(sqlx::query_as::<_, {struct}>(&sql).bind(id).fetch_optional(pool).await?)",
            "        })",
            "    }",
            "",
            "    /// Read every row, including ones marked deleted.",
            f"    pub async fn list(store: &Store) -> Result<Vec<{struct}>, StoreError> {{",
            "        dispatch!(store, |pool| {",
            f"            Ok(sqlx::query_as::<_, {struct}>(SELECT_ALL).fetch_all(pool).await?)",
            "        })",
            "    }",
            "",
            "    /// Remove a row outright.  Most callers want the soft delete the model uses instead.",
            "    pub async fn delete(store: &Store, id: i64) -> Result<(), StoreError> {",
            "        let sql = store.placeholders(DELETE);",
            "        dispatch!(store, |pool| {",
            "            sqlx::query(&sql).bind(id).execute(pool).await?;",
            "            Ok(())",
            "        })",
            "    }",
        ]
        if any(column["name"] == "deleted" for column in table["columns"]):
            out += [
                "",
                "    /// Mark a row deleted, as the C++ does: rows are kept so that recipes referring to",
                "    /// them still resolve, and are simply hidden from the lists.",
                "    pub async fn soft_delete(store: &Store, id: i64, deleted: bool) -> Result<(), StoreError> {",
                f"        let sql = store.placeholders(\"UPDATE {table['name']} SET deleted = ? WHERE {primary_key} = ?\");",
                "        dispatch!(store, |pool| {",
                "            sqlx::query(&sql).bind(deleted).bind(id).execute(pool).await?;",
                "            Ok(())",
                "        })",
                "    }",
            ]
        out += ["}", ""]
    return "\n".join(out)


def generate_routes(schema: dict) -> str:
    """One resource group per table, built on the generated repositories."""
    out = [
        HEADER.format(file="routes.rs", sources="schema/v23.json"),
        "",
        "//! A resource group per table.",
        "//!",
        "//! Five routes each -- list, create, read, update, delete -- over the repositories in",
        "//! `bt-store`.  Generated, because thirty-nine near-identical modules written by hand would",
        "//! be thirty-nine chances to get one wrong.",
        "//!",
        "//! Every handler takes its store from the request's state rather than a global, so the",
        "//! session layer Stage 2 adds wraps these without any of them changing (PLAN.md §3.3).",
        "",
        "use axum::extract::{Path, State};",
        "use axum::routing::get;",
        "use axum::{Json, Router};",
        "use bt_model::tables::*;",
        "use bt_store::tables;",
        "",
        "use crate::error::{ApiError, ApiResult};",
        "use crate::state::AppState;",
        "",
    ]

    for table in schema["tables"]:
        struct = pascal_case(table["name"]) + "Row"
        module = table["name"]
        singular = table["cpp_type"]
        out += [
            f"/// `/api/{module}`",
            f"pub mod {module} {{",
            "    use super::*;",
            "",
            f"    pub fn routes() -> Router<AppState> {{",
            f'        Router::new().route("/", get(list).post(create)).route("/{{id}}", get(read).put(update).delete(remove))',
            "    }",
            "",
            f"    async fn list(State(state): State<AppState>) -> ApiResult<Json<Vec<{struct}>>> {{",
            f"        Ok(Json(tables::{module}::list(state.store()).await?))",
            "    }",
            "",
            f"    async fn read(State(state): State<AppState>, Path(id): Path<i64>) -> ApiResult<Json<{struct}>> {{",
            f"        tables::{module}::get(state.store(), id)",
            "            .await?",
            "            .map(Json)",
            f'            .ok_or_else(|| ApiError::NotFound(format!("no {singular} with id {{id}}")))',
            "    }",
            "",
            f"    async fn create(State(state): State<AppState>, Json(row): Json<{struct}>) -> ApiResult<Json<{struct}>> {{",
            f"        let id = tables::{module}::insert(state.store(), &row).await?;",
            f"        read(State(state), Path(id)).await",
            "    }",
            "",
            "    async fn update(",
            "        State(state): State<AppState>,",
            "        Path(id): Path<i64>,",
            f"        Json(mut row): Json<{struct}>,",
            f"    ) -> ApiResult<Json<{struct}>> {{",
            "        // The key in the path is the one that counts; a body claiming another is a",
            "        // mistake rather than a way to move a row.",
            "        row.id = id;",
            f"        if tables::{module}::get(state.store(), id).await?.is_none() {{",
            f'            return Err(ApiError::NotFound(format!("no {singular} with id {{id}}")));',
            "        }",
            f"        tables::{module}::update(state.store(), &row).await?;",
            f"        read(State(state), Path(id)).await",
            "    }",
            "",
            "    async fn remove(State(state): State<AppState>, Path(id): Path<i64>) -> ApiResult<axum::http::StatusCode> {",
        ]
        if any(column["name"] == "deleted" for column in table["columns"]):
            out += [
                "        // Deleting is soft: the row stays so that anything referring to it still",
                "        // resolves, and is simply hidden from the lists.",
                f"        tables::{module}::soft_delete(state.store(), id, true).await?;",
            ]
        else:
            out += [f"        tables::{module}::delete(state.store(), id).await?;"]
        out += [
            "        Ok(axum::http::StatusCode::NO_CONTENT)",
            "    }",
            "}",
            "",
        ]

    out += [
        "/// Every generated resource group, mounted under its table's name.",
        "pub fn table_routes() -> Router<AppState> {",
        "    Router::new()",
    ]
    for table in schema["tables"]:
        out.append(f'        .nest("/{table["name"]}", {table["name"]}::routes())')
    out += ["}", ""]
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=pathlib.Path, required=True, help="directory for the bt-model files")
    parser.add_argument("--store-out", type=pathlib.Path, help="directory for the bt-store repository files")
    parser.add_argument("--api-out", type=pathlib.Path, help="directory for the bt-api route files")
    args = parser.parse_args()

    schema = json.loads((REPO / "schema" / "v23.json").read_text(encoding="utf-8"))
    enums = json.loads((REPO / "schema" / "enums.json").read_text(encoding="utf-8"))

    args.out.mkdir(parents=True, exist_ok=True)
    files = {"enums.rs": generate_enums(enums), "tables.rs": generate_tables(schema)}
    files["mod.rs"] = (
        HEADER.format(file="mod.rs", sources="schema/v23.json and schema/enums.json")
        + "\n//! Generated model code.  See `tools/generate-model.py`.\n\npub mod enums;\npub mod tables;\n"
    )
    targets = [(args.out, files)]
    if args.store_out:
        args.store_out.mkdir(parents=True, exist_ok=True)
        targets.append(
            (
                args.store_out,
                {
                    "tables.rs": generate_store(schema),
                    "mod.rs": HEADER.format(file="mod.rs", sources="schema/v23.json")
                    + "\n//! Generated repositories.  See `tools/generate-model.py`.\n\npub mod tables;\n",
                },
            )
        )

    if args.api_out:
        args.api_out.mkdir(parents=True, exist_ok=True)
        targets.append(
            (
                args.api_out,
                {
                    "routes.rs": generate_routes(schema),
                    "mod.rs": HEADER.format(file="mod.rs", sources="schema/v23.json")
                    + "\n//! Generated routes.  See `tools/generate-model.py`.\n\npub mod routes;\n",
                },
            )
        )

    written = []
    for directory, group in targets:
        for name, content in group.items():
            path = directory / name
            path.write_text(content.rstrip("\n") + "\n", encoding="utf-8")
            written.append(path)
            print(f"wrote {path}")

    # Format what was generated, so that the committed files are byte-identical to a fresh run and
    # `cargo fmt --check` has nothing to say about them.
    rustfmt = shutil.which("rustfmt")
    if rustfmt:
        # Point rustfmt at the workspace config explicitly: it searches upwards from each file,
        # so generating into a scratch directory would otherwise use different settings and the
        # output would not match what is committed.
        config = REPO / "rust" / "rustfmt.toml"
        subprocess.run(
            [rustfmt, "--edition", "2024", "--config-path", str(config), *[str(path) for path in written]],
            check=True,
        )
        print(f"formatted {len(written)} files")
    else:
        print("warning: rustfmt not found; generated files are unformatted", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
